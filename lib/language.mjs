export function translate(value, language) {
 if (typeof value !== 'string') return value;
 const key = value.trim();
 const translated = (language === 'en' ? english : chinese)[key];
 if (translated) return value.replace(key, translated);
 if (language === 'en') return value.replace(/(\d+) 个结果/g, '$1 results').replace(/(\d+ \/ \d+) 题已理解/g, '$1 questions understood').replace(/ · 课程$/,' · Course').replace(/ · 示例$/,' · Sample');
 return value;
}
